n = int(input("Entrez un entier : "))

print(f"Résultat de n / 4  : {n / 4}")   # Division flottante (donne un décimal)
print(f"Résultat de n // 4 : {n // 4}")  # Division entière (garde uniquement le quotient)

# Explication : 
# / est l'opérateur de division classique.
# // est l'opérateur de division entière (tronque la partie décimale).